function loadSettings() {
  try {
    const data = store.read('system_settings');
    return { ...DEFAULT_SETTINGS, ...(data && typeof data === 'object' ? data : {}) };
  } catch (err) {
    console.warn(`[Settings] ⚠️ Error reading settings: ${err.message}`);
    return { ...DEFAULT_SETTINGS };
  }
}

function saveSettings(settings) {
  try {
    const current = loadSettings();
    const incoming = { ...settings };
    // Display-only fields (generated by publicBuffSettings) must not be saved
    delete incoming.telegramBotTokenMasked;
    delete incoming.hasBotToken;
    delete incoming.botInfo;
    // The API never returns the real token to the UI, so an empty token means "keep it", not "delete"
    if (!incoming.telegramBotToken) delete incoming.telegramBotToken;
    const updated = { ...current, ...incoming };
    store.write('system_settings', updated);
    try {
      const db = require('./db');
      db.syncTelegramSettingsToDb(updated).catch(() => {});
    } catch (_) {}
    return updated;
  } catch (err) {
    console.error(`[Settings] ❌ Error writing settings: ${err.message}`);
    return null;
  }
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** Sends 1 message; retries up to 2 times on network errors / Telegram overload (5xx, 429) */
async function sendTelegramMessage(text, parseMode = 'HTML', replyMarkup = null) {
  const settings = loadSettings();
  const token = settings.telegramBotToken;
  const chatId = settings.telegramChatId;

  if (!token || !chatId) {
    return { success: false, reason: 'Telegram Bot Token or Chat ID is not configured' };
  }

  const url = `https://api.telegram.org/bot${token}/sendMessage`;
  const maxAttempts = 3;
  let lastErr = '';

  const cleanText = (text || '').replace(/<[^>]*>/g, '');
  const firstLine = (text || '').split('\n')[0]?.replace(/<[^>]*>/g, '')?.trim() || 'Telegram notification';
  let eventType = 'GENERAL';
  const upper = (text || '').toUpperCase();
  if (upper.includes('BUFF HOÀN TẤT') || upper.includes('CHIẾN DỊCH') || upper.includes('BUFF CAMPAIGN COMPLETE') || upper.includes('CAMPAIGN')) eventType = 'BUFF_COMPLETED';
  else if (upper.includes('CHECKPOINT') || (upper.includes('VIA') && (upper.includes('HẾT HẠN') || upper.includes('EXPIRED')))) eventType = 'VIA_DEAD';
  else if (upper.includes('HẠN CHẾ') || upper.includes('ACTION_BLOCKED') || upper.includes('CHẶN') || upper.includes('QUÁ NHANH') || upper.includes('RESTRICT') || upper.includes('ACTION BLOCKED') || upper.includes('TOO FAST')) eventType = 'ACTION_BLOCKED';
  else if (upper.includes('KHẨN CẤP') || upper.includes('DỪNG') || upper.includes('EMERGENCY')) eventType = 'EMERGENCY_STOP';
  else if (upper.includes('BÀI VIẾT MỚI') || upper.includes('HUNTER') || upper.includes('NEW POST')) eventType = 'HUNTER';
  else if (upper.includes('HÀNG ĐỢI') || upper.includes('QUEUE')) eventType = 'QUEUE_IDLE';
  else if (upper.includes('TEST') || upper.includes('XÁC NHẬN KẾT NỐI') || upper.includes('CONNECTION CONFIRMED')) eventType = 'TEST';

  const payload = {
    chat_id: chatId,
    text,
    parse_mode: parseMode,
    disable_web_page_preview: true,
  };
  if (replyMarkup) {
    payload.reply_markup = typeof replyMarkup === 'string' ? JSON.parse(replyMarkup) : replyMarkup;
  }

  for (let attempt = 1; attempt <= maxAttempts; attempt++) {
    try {
      const res = await axios.post(url, payload, { timeout: 8000 });
      const msgId = res.data?.result?.message_id || null;
      try {
        const db = require('./db');
        await db.saveTelegramNotification({
          chatId,
          eventType,
          title: firstLine,
          message: cleanText,
          status: 'SENT',
          telegramMessageId: msgId,
        });
      } catch {}
      return { success: true, data: res.data };
    } catch (err) {
      const status = err.response?.status;
      lastErr = err.response?.data?.description || err.message;
      const retryable = !status || status >= 500 || status === 429;
      if (!retryable || attempt === maxAttempts) break;
      const wait = status === 429 ? (err.response?.data?.parameters?.retry_after || 3) * 1000 : attempt * 1500;
      await sleep(Math.min(wait, 10000));
    }
  }
  console.warn(`[Telegram] ⚠️ Could not send the message: ${lastErr}`);
  try {
    const db = require('./db');
    await db.saveTelegramNotification({
      chatId,
      eventType,
      title: firstLine,
      message: cleanText,
      status: 'FAILED',
      errorMessage: lastErr,
    });
  } catch {}
  return { success: false, reason: lastErr };
}

/**
 * Sends a photo via Telegram (used for proof screenshot reports)
 */
async function sendTelegramPhoto(photoPathOrBuffer, caption = '', { parseMode = 'HTML', replyMarkup = null } = {}) {
  const settings = loadSettings();
  const token = settings.telegramBotToken;
  const chatId = settings.telegramChatId;

  if (!token || !chatId) {
    return { success: false, reason: 'Telegram Bot Token or Chat ID is not configured' };
  }

  const url = `https://api.telegram.org/bot${token}/sendPhoto`;
  try {
    const formData = new FormData();
    formData.append('chat_id', chatId);

    if (typeof photoPathOrBuffer === 'string') {
      if (fs.existsSync(photoPathOrBuffer)) {
        const fileBuf = fs.readFileSync(photoPathOrBuffer);
        formData.append('photo', new Blob([fileBuf]), path.basename(photoPathOrBuffer));
      } else {
        console.warn(`[Telegram] ⚠️ Photo file doesn't exist, falling back to text: ${photoPathOrBuffer}`);
        if (caption) return sendTelegramMessage(caption, parseMode, replyMarkup);
        return { success: false, reason: 'File does not exist' };
      }
    } else if (Buffer.isBuffer(photoPathOrBuffer)) {
      formData.append('photo', new Blob([photoPathOrBuffer]), 'proof.png');
    }

    if (caption) {
      // Telegram captions are limited to 1024 characters
      const safeCaption = caption.length > 1000 ? caption.slice(0, 995) + '...' : caption;
      formData.append('caption', safeCaption);
      formData.append('parse_mode', parseMode);
    }

    if (replyMarkup) {
      formData.append(
        'reply_markup',
        typeof replyMarkup === 'string' ? replyMarkup : JSON.stringify(replyMarkup)
      );
    }

    const res = await axios.post(url, formData, {
      headers: { 'Content-Type': 'multipart/form-data' },
      timeout: 35000,
    });

    console.log('[Telegram] 📸 Proof photo sent to Telegram!');
    return { success: true, data: res.data };
  } catch (err) {
    const errMsg = err.response?.data?.description || err.message;
    console.warn(`[Telegram] ⚠️ Error sending photo: ${errMsg}, falling back to a text message.`);
    if (caption) {
      await sendTelegramMessage(caption, parseMode, replyMarkup);
    }
    return { success: false, reason: errMsg };
  }
}

